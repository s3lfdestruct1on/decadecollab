// догадайся блять че делает 
func DeleteUser(id int)error{
	defer conn.Close(context.Background())
	query := "DELETE FROM users WHERE id = $1"

	_,err := conn.Exec(context.Background(),query,id)
	if err != nil{
		return fmt.Errorf("user not found: %w", err)
	}
	return nil
}
// возвращает одного юзера по айди
func GetUser(id int) (*models.User,error){
	user := models.User{}
	query := "SELECT * FROM users WHERE id = $1"

	err := conn.QueryRow(context.Background(),query,id).Scan(&user.Id,&user.Username,&user.Password,&user.Email)
	if err != nil{
		return nil,fmt.Errorf("user not found: %w", err)
	}
	return &user,nil
}
// возвращает страницу(10) пользователей
func GetUsersPaging(page int)([]models.User,error){
	pagesize := 10
	offset := page-1
	var res []models.User
	query := "SELECT * FROM users limit $1 offset $2"

	rows,err := conn.Query(context.Background(),query,pagesize,offset)
	if err != nil{
		return nil, fmt.Errorf("failed to run query: %w",err)
	}

	for rows.Next(){
		user := models.User{}
		err := rows.Scan(&user.Id,&user.Username,&user.Password,&user.Email)
		if err != nil{
			return nil,fmt.Errorf("failed to scan user %w",err)
		}
		res = append(res, user)
	}
	return res,nil
}
// возвращает всех пользователй в диапазоне from - от, to - до, e.g. from 100 to 150 вернет 50 пользователей начиная с 100
func GetUsersFromTo(from int,to int)([]models.User,error){
	limit := to - from
	var res []models.User
	query := "SELECT * FROM users limit $1 offset $2"

	rows,err := conn.Query(context.Background(),query,limit,from)
	if err != nil{
		return nil, fmt.Errorf("failed to run query: %w",err)
	}
	for rows.Next(){
		user := models.User{}
		err := rows.Scan(&user.Id,&user.Username,&user.Password,&user.Email)
		if err != nil{
			return nil,fmt.Errorf("failed to scan user %w",err)
		}
		res = append(res, user)
	}
	return res,nil
}