//sdelai logger :D
func CreateUsersTable(conn *pgx.Conn) error {
    query := `
	CREATE TABLE IF NOT EXISTS users (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(255) NOT NULL,
        password VARCHAR(255) NOT NULL,
        email VARCHAR(255) UNIQUE NOT NULL
    );`
    _, err := conn.Exec(context.Background(), query)
    if err != nil {
        return fmt.Errorf("failed to create users table: %w", err)
    }
    
    return nil
}
//add logger :)
func CreateUser(conn *pgx.Conn,username string,password string,email string)(int,error){
 	query := "INSERT INTO users (name,password,email) values($1,$2,$3) RETURNING id"
	var id int
	err := conn.QueryRow(context.Background(),query,username,password,email).Scan(&id)
	if err != nil {
        return 0,fmt.Errorf("failed to add user: %w", err)
    }
	return id,nil
}
