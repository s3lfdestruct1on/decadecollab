package postgre

import (
	"context"
	"decadecollab/internal/config"
	"decadecollab/internal/models"
	"fmt"
	"os"
		db "decadecollab/internal/storage"
)


var(
	sqlcfg = config.PSQLConfig{
	Port: os.Getenv("PORT"),
	Username: os.Getenv("USERDB"),
	Password: os.Getenv("PASS"),
	Database: os.Getenv("DB"),
}
conn,_ = db.DBConn(sqlcfg)

)
//sdelai logger :D
func InitDB() error {
    query := `
	CREATE TABLE IF NOT EXISTS users (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(255) NOT NULL,
        password VARCHAR(255) NOT NULL,
        email VARCHAR(255) UNIQUE NOT NULL
    );`
    _, err := conn.Exec(context.Background(), query)
    if err != nil {
        return fmt.Errorf("failed to create users table: %w", err)
    }
    
    return nil
}
//add logger :)
func CreateUser(username string,password string,email string)(int,error){
 	query := "INSERT INTO users (name,password,email) values($1,$2,$3) RETURNING id"
	var id int
	err := conn.QueryRow(context.Background(),query,username,password,email).Scan(&id)
	if err != nil {
        return 0,fmt.Errorf("failed to add user: %w", err)
    }
	return id,nil
}
//dobav' logger :-D
func UpdateUser(id int,username string,password string,email string)error{
	query := "UPDATE users SET name = $1,password = $2, email = $3 where id = $4"

	_,err := conn.Exec(context.Background(),query,username,password,email,id)
	if err != nil {
        return fmt.Errorf("failed to create users table: %w", err)
    }
	return nil
}
// logger namuti :-)
func DeleteUser(id int)error{
	defer conn.Close(context.Background())
	query := "DELETE FROM users WHERE id = $1"

	_,err := conn.Exec(context.Background(),query,id)
	if err != nil{
		return fmt.Errorf("user not found: %w", err)
	}
	return nil
}
//dai logger :*
func GetUser(id int) (*models.User,error){
	user := models.User{}
	query := "SELECT * FROM users WHERE id = $1"

	err := conn.QueryRow(context.Background(),query,id).Scan(&user.Id,&user.Username,&user.Password,&user.Email)
	if err != nil{
		return nil,fmt.Errorf("user not found: %w", err)
	}
	return &user,nil
}